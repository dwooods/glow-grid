"""Write web/js/examples_data.js: the original example sprites, as data the Board card can send to an ESP32-C3.

The sprites are drawn as text in examples/sprites.py; this turns them into a small JS file (palette + one 256-character
string per frame) so the editor does not need Python. tests/test_web_examples.py regenerates it and fails if the
committed file is stale, and checks that the .gg bytes the editor builds from it equal gg_format.pack() of the source.

Run from the repo root after changing a sprite:  python3 examples/make_web_examples.py
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from make_examples import BRIGHTNESS, EXAMPLES, GAMMA  # noqa: E402
from sprites import PALETTE  # noqa: E402

OUT = os.path.join(os.path.dirname(HERE), "web", "js", "examples_data.js")
STILL_FPS = 6          # a one-frame sprite never animates; any legal speed will do
BOARD_SUFFIX = "_sprite"


def board_name(name):
    return name + BOARD_SUFFIX


def entries():
    out = []
    for name, (frames, fps) in EXAMPLES.items():
        flat = ["".join(f) for f in frames]
        used = sorted(set("".join(flat)))
        out.append({
            "name": board_name(name),
            "fps": fps or STILL_FPS,
            "palette": {c: "#%02x%02x%02x" % PALETTE[c] for c in used},
            "frames": flat,
        })
    return out


def render():
    lines = [
        "// GENERATED by examples/make_web_examples.py from examples/sprites.py. Do not edit; tests/test_web_examples.py checks it.",
        "// Each example: board name, speed, palette (character -> color) and one 256-character string per frame (16 rows of 16).",
        f"const GG_EXAMPLE_BRIGHTNESS = {BRIGHTNESS}, GG_EXAMPLE_GAMMA = {GAMMA};",
        "const GG_EXAMPLES = [",
    ]
    for e in entries():
        lines.append("  " + json.dumps(e, separators=(", ", ": ")) + ",")
    lines.append("];")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    with open(OUT, "w", newline="\n") as fh:
        fh.write(render())
    print(f"wrote {os.path.relpath(OUT)} ({os.path.getsize(OUT):,} bytes, {len(EXAMPLES)} examples)")
