"""Write web/js/examples_legacy.js: a fingerprint (name, CRC, size) of every earlier version of every example the editor
has ever shipped, so Remove examples can still recognise an old copy on a board (and an example that was retired, like
bunny_sprite) and tell it from a sprite of yours.

Without this, a redesigned example (the new mushroom, say) looks like "a sprite you changed" and is kept for ever. The
list is rebuilt from the git history of web/js/examples_data.js plus the working copy, so it needs no upkeep except
this command after the examples change:

    python3 examples/make_web_examples.py && python3 examples/make_legacy_examples.py

Run from inside the repo (needs git and Node). tests/test_web_examples.py checks the file is current.
"""
import json
import os
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
DATA = "web/js/examples_data.js"
OUT = os.path.join(ROOT, "web", "js", "examples_legacy.js")
NODE_SCRIPT = os.path.join(ROOT, "tests", "example_bytes.js")


def fingerprints(path):
    """[(name, crc, size)] for one copy of the data file, or None if that copy does not build (an old transcription slip)."""
    run = subprocess.run(["node", NODE_SCRIPT, path], capture_output=True, text=True)
    if run.returncode:
        return None
    return [(d["name"], d["crc"], len(d["hex"]) // 2) for d in json.loads(run.stdout)]


def history():
    out = subprocess.run(["git", "log", "--format=%H", "--", DATA], cwd=ROOT, check=True, capture_output=True, text=True).stdout
    return out.split()


def collect():
    current = fingerprints(os.path.join(ROOT, DATA))
    assert current, "the working copy of examples_data.js does not build"
    now = {n: (c, s) for n, c, s in current}
    seen = set()
    with tempfile.TemporaryDirectory() as tmp:
        for i, rev in enumerate(history()):
            text = subprocess.run(["git", "show", f"{rev}:{DATA}"], cwd=ROOT, check=True, capture_output=True).stdout
            path = os.path.join(tmp, f"data_{i}.js")
            with open(path, "wb") as fh:
                fh.write(text)
            for n, c, s in fingerprints(path) or []:
                if now.get(n) != (c, s):          # not what the editor ships today
                    seen.add((n, c, s))
    return sorted(seen)


def render(entries):
    lines = [
        "// GENERATED by examples/make_legacy_examples.py. Do not edit; tests/test_web_examples.py checks it.",
        "// [name, CRC, size] of every earlier version of an example, and of retired examples, so Remove examples can still tell them from your own sprites.",
        "const GG_LEGACY_EXAMPLES = [",
    ]
    for n, c, s in entries:
        lines.append(f'  ["{n}", "{c}", {s}],')
    lines.append("];")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    entries = collect()
    with open(OUT, "w", newline="") as fh:
        fh.write(render(entries))
    print(f"wrote {os.path.relpath(OUT, ROOT)}: {len(entries)} old versions of {len({n for n, _, _ in entries})} examples")
