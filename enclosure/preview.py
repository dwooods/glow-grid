gridA=T(grid,dz=ZL+PANEL_T)
flipx=trimesh.transformations.rotation_matrix(np.pi,[1,0,0])
coverA=T(cover,dz=H+CT,rot=flipx)       # plate face at the front, lip back over the frame walls
# frame -> cradle coordinates (x, u, v): a = frame z (depth), b = frame y + HO (height above the frame's bottom edge)
def to_cradle(m):
    m=m.copy(); V=m.vertices.copy(); x,y,z=V[:,0],V[:,1],V[:,2]; a=z; b=y+HO
    m.vertices=np.c_[x, a*c-b*s, a*s+b*c+6.0]; return m
