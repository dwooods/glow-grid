"""Renders enclosure/build.py's parts to one preview PNG (eight shaded views: frame front and back, holder and cap, exploded stack, on the cradle, cradle).
Usage: cd enclosure && python3 preview.py [output_dir]   (runs build.py first; needs matplotlib on top of build.py's packages)
"""
import sys,io,contextlib,numpy as np
sys.argv=['build.py',sys.argv[1] if len(sys.argv)>1 else 'out']
with contextlib.redirect_stdout(io.StringIO()):
    exec(open('build.py').read())
import matplotlib; matplotlib.use('Agg'); import matplotlib.pyplot as plt
from mpl_toolkits.mplot3d.art3d import Poly3DCollection
L=np.array([0.3,-0.5,0.8]); L/=np.linalg.norm(L)
def fine(m,e=12.0):
    v,f=trimesh.remesh.subdivide_to_size(m.vertices,m.faces,max_edge=e); return trimesh.Trimesh(v,f,process=False)
def shaded(ax,m,rgb,alpha=1.0):
    if len(m.faces)<6000: m=fine(m)
    n=m.face_normals; k=0.42+0.58*np.clip(n@L,0,1)
    cols=np.clip(np.array(rgb)[None,:]*k[:,None],0,1)
    ax.add_collection3d(Poly3DCollection(m.vertices[m.faces],facecolors=cols,edgecolors='none',alpha=alpha,zsort='average'))
def view(ax,lim,elev,azim,title):
    (x0,x1),(y0,y1),(z0,z1)=lim; ax.set_xlim(x0,x1); ax.set_ylim(y0,y1); ax.set_zlim(z0,z1); ax.set_box_aspect((x1-x0,y1-y0,z1-z0)); ax.view_init(elev=elev,azim=azim); ax.set_axis_off(); ax.set_title(title,fontsize=10,loc='left',fontweight='bold')
def T(m,dx=0,dy=0,dz=0,rot=None):
    m=m.copy()
    if rot is not None: m.apply_transform(rot)
    m.apply_translation([dx,dy,dz]); return m
BLUE=(0.16,0.30,0.62); TEAL=(0.20,0.60,0.56); ORANGE=(0.95,0.56,0.17); GREY=(0.80,0.80,0.80); BLACK=(0.12,0.12,0.12); WHITE=(0.93,0.93,0.93); BOARD=(0.30,0.47,0.65); GREEN=(0.15,0.40,0.22)
