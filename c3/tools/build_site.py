#!/usr/bin/env python3
"""Packs the Glow Grid editor (../web) into one gzipped page and writes it into the firmware sketch folder, so the board can serve the
editor itself at http://glowgrid.local/ (firmware 12). iPhone Safari will not let the https editor call a plain-http board; a page the
board serves shares the board's origin, so the same editor works there.

    python3 c3/tools/build_site.py            rebuild c3/c3_player/site_data.h and site_b64_*.h from web/
    python3 c3/tools/build_site.py --check    exit 1 if the generated files are missing or differ from what web/ would give now

What is packed: index.html with style.css and every js/*.js inlined, minus the service worker, manifest and icon links (a service worker
cannot register on a plain-http page, and the board does not serve icons). Nothing is minified. The gzip is stored as base64 text in C string
literals (two part files), and the firmware decodes it a piece at a time while sending it, so it needs no RAM for the page.
The generated files are git-ignored. Run this script before flashing; without them the sketch still builds and the board answers / with a note.
The board's copy is only as new as the last run of this script and the last flash: rebuild and re-flash when you want the board's editor updated.
"""
import base64, gzip, os, re, sys, zlib

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, '..', '..'))
WEB = os.path.join(ROOT, 'web')
SKETCH = os.path.join(ROOT, 'c3', 'c3_player')
PART_CHARS = 40000          # base64 characters per part file: keeps each file under about 42 KB so one push call carries one file
LINE_CHARS = 76


def read(path):
    with open(path, encoding='utf-8') as f:
        return f.read()


def build_marker():
    """The service worker's cache name, e.g. glow-grid-v49: the page says which editor build it is."""
    m = re.search(r"const CACHE = '([^']+)'", read(os.path.join(WEB, 'sw.js')))
    return m.group(1) if m else 'unknown'


def bundle_html():
    html = read(os.path.join(WEB, 'index.html'))
    for rel in (r'<link rel="manifest"[^>]*>\n', r'<link rel="icon"[^>]*>\n', r'<link rel="apple-touch-icon"[^>]*>\n'):
        html, n = re.subn(rel, '', html)
        if n != 1:
            raise SystemExit(f'web/index.html changed: expected exactly one match for {rel}')

    def inline_css(m):
        css = read(os.path.join(WEB, m.group(1)))
        if '</style' in css.lower():
            raise SystemExit(f'{m.group(1)} contains </style>')
        return f'<style>\n{css}</style>'
    html, n = re.subn(r'<link rel="stylesheet" href="(style\.css)">', inline_css, html)
    if n != 1:
        raise SystemExit('web/index.html changed: the style.css link was not found exactly once')

    def inline_js(m):
        js = read(os.path.join(WEB, m.group(1)))
        if '</script' in js.lower():
            raise SystemExit(f'{m.group(1)} contains </script>')
        return f'<script>\n{js}</script>'
    html, n = re.subn(r'<script src="(js/[^"]+)"></script>', inline_js, html)
    if n < 5:
        raise SystemExit('web/index.html changed: the script tags were not found')
    marker = f'<meta name="gg-site" content="{build_marker()}">\n'
    html = html.replace('<title>', marker + '<title>', 1)
    return html


def build_files():
    """{file name: text} for everything this script writes."""
    gz = gzip.compress(bundle_html().encode('utf-8'), compresslevel=9, mtime=0)
    b64 = base64.b64encode(gz).decode('ascii')
    parts = [b64[i:i + PART_CHARS] for i in range(0, len(b64), PART_CHARS)]
    files = {}
    for k, p in enumerate(parts):
        lines = [p[i:i + LINE_CHARS] for i in range(0, len(p), LINE_CHARS)]
        files[f'site_b64_{k}.h'] = ''.join(f'"{l}"\n' for l in lines)
    inc = ''.join(f'#include "site_b64_{k}.h"\n' for k in range(len(parts)))
    files['site_data.h'] = (
        '// Generated by c3/tools/build_site.py from web/. Do not edit: run the script again.\n'
        '// The editor page, gzipped, as base64 text; the firmware decodes it while sending it (see httpSite in c3_player.ino).\n'
        '#pragma once\n'
        f'#define GG_SITE_LEN {len(gz)}                 // bytes after decoding (the gzip file)\n'
        f'#define GG_SITE_CRC 0x{zlib.crc32(gz) & 0xffffffff:08x}UL         // CRC-32 of those bytes\n'
        f'#define GG_SITE_BUILD "{build_marker()}"      // the web/sw.js cache name this was built from\n'
        'static const char GG_SITE_B64[] =\n' + inc + ';\n')
    return files


def main():
    files = build_files()
    old = sorted(f for f in os.listdir(SKETCH) if re.fullmatch(r'site_b64_\d+\.h', f))
    if '--check' in sys.argv:
        bad = [n for n, t in files.items() if not os.path.exists(os.path.join(SKETCH, n)) or read(os.path.join(SKETCH, n)) != t]
        bad += [n for n in old if n not in files]
        if bad:
            print('out of date: ' + ', '.join(bad) + ' (run c3/tools/build_site.py)')
            return 1
        print('up to date: ' + build_marker())
        return 0
    for n in old:
        if n not in files:
            os.remove(os.path.join(SKETCH, n))
    for n, t in files.items():
        with open(os.path.join(SKETCH, n), 'w', encoding='utf-8', newline='\n') as f:
            f.write(t)
    print(f'wrote {len(files)} files for build {build_marker()}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
