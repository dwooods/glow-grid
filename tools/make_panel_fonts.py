#!/usr/bin/env python3
"""Writes web/js/panel_fonts.js: the bitmap letters the experimental Bluetooth panel card draws text with (web/js/panel.js).

    python3 tools/make_panel_fonts.py FONT_DIR [DEJAVU_DIR]

FONT_DIR holds PressStart2P-Regular.ttf, Jersey15-Regular.ttf and Jersey20-Regular.ttf (SIL Open Font License; from
https://github.com/google/fonts/tree/main/ofl). DEJAVU_DIR holds DejaVuSans-Bold.ttf and DejaVuSansMono-Bold.ttf (default /usr/share/fonts/truetype/dejavu/).
Needs Pillow. Each letter is rendered without anti-aliasing at a size where the font lines up with the pixel grid, then stored as
bits, so the panel never gets a letter with a stray pixel. See THIRD_PARTY_NOTICES.md for the font licences.
"""
import json, os, sys
from PIL import Image, ImageDraw, ImageFont
F=sys.argv[1].rstrip('/')+'/'
D=(sys.argv[2] if len(sys.argv)>2 else '/usr/share/fonts/truetype/dejavu/').rstrip('/')+'/'
chars=[chr(c) for c in range(32,127)]
SPECS=[
 ('DejaVu Bold',D+'DejaVuSans-Bold.ttf',None,[26,19,15,12,10,9,8,7],'dejavu'),
 ('Press Start 2P',F+'PressStart2P-Regular.ttf',None,[16,8],None),
 ('Jersey 15',F+'Jersey15-Regular.ttf',None,[27,18,13,9],None),
 ('Jersey 20',F+'Jersey20-Regular.ttf',None,[20,14,10],None),
]
def font(fp,var,sz):
    f=ImageFont.truetype(fp,sz)
    if var:
        try:f.set_variation_by_axes(var)
        except Exception:pass
    return f
def render(f,ch,w,h,base):
    im=Image.new('1',(w,h),0);d=ImageDraw.Draw(im);d.fontmode='1';d.text((0,base),ch,font=f,fill=1,anchor='ls');return im
out={}
for name,fp,var,sizes,kind in SPECS:
    entry={'fit':{}}
    # fit tables
    for sz in sizes:
        f=font(fp,var,sz);asc,desc=f.getmetrics();H=asc+desc+2;base=asc+1
        g={}
        for ch in chars:
            adv=max(1,round(f.getlength(ch)));im=render(f,ch,adv+8,H,base)
            right=max([x+1 for x in range(adv+8) for y in range(H) if im.getpixel((x,y))] or [0])
            a=min(30,max(adv,right));im=im.crop((0,0,a,H))
            dg=(a+3)//4
            rows=[sum(1<<(a-1-x) for x in range(a) if im.getpixel((x,y))) for y in range(H)]
            g[ch]=[a,''.join(('%0'+str(dg)+'x')%r for r in rows)]
        ink=[y for y in range(H) if any(int(v[1][y*((v[0]+3)//4):(y+1)*((v[0]+3)//4)] or '0',16) for v in g.values() if ch!=' ')]
        t,b=min(ink),max(ink)+1
        for k,v in g.items():
            dg=(v[0]+3)//4;v[1]=v[1][t*dg:b*dg]
        if b-t<=32: entry['fit'][str(sz)]={'h':b-t,'g':g}
    # cell table
    cell={}
    if kind=='dejavu':
        fm=ImageFont.truetype(D+'DejaVuSansMono-Bold.ttf',14)
        for ch in chars:
            im=render(fm,ch,8,16,13);rows=[]
            for y in range(32):
                r=0
                for x in range(16):
                    if im.getpixel((x//2,y//2)): r|=1<<(15-x)
                rows.append(r)
            cell[ch]=''.join('%04x'%r for r in rows)
    else:
        chosen=None
        for sz in sizes:
            f=font(fp,var,sz);asc,desc=f.getmetrics()
            if max(f.getlength(c) for c in 'abcdefghijklmnopqrstuvwxyzMW')<=16.5 and asc+desc<=34: chosen=sz;break
        if chosen is None: chosen=sizes[-1]
        f=font(fp,var,chosen);asc,desc=f.getmetrics()
        # vertical centering from ink extent of tall+descending letters
        probe=render(f,'hgy',48,asc+desc+8,asc+4)
        ys=[y for y in range(probe.height) for x in range(48) if probe.getpixel((x,y))]
        top,bot=min(ys),max(ys)+1;ink_h=bot-top
        off=max(0,(32-ink_h)//2)-top  # shift so ink centered
        for ch in chars:
            im=render(f,ch,24,40,asc+4+off+4)  # extra 4 slack rows
            # find x extent to center horizontally within 16
            xs=[x for x in range(24) for y in range(40) if im.getpixel((x,y))]
            sx=0
            if xs: sx=max(-min(xs),(16-(max(xs)+min(xs)+1))//2) if (max(xs)-min(xs)+1)<=16 else -min(xs)
            rows=[]
            for y in range(32):
                r=0
                for x in range(16):
                    xx=x-sx
                    if 0<=xx<24 and im.getpixel((xx,y+4)): r|=1<<(15-x)
                rows.append(r)
            cell[ch]=''.join('%04x'%r for r in rows)
        entry['cellsize']=chosen
    entry['cell']=cell
    out[name]=entry
    print(name,'cell size',entry.get('cellsize','2x14'),'fit sizes',list(entry['fit'].keys()))
js='// Generated by tools/make_panel_fonts.py from DejaVu Sans Bold, DejaVu Sans Mono Bold, Press Start 2P, Jersey 15 and Jersey 20 (see THIRD_PARTY_NOTICES.md). Bitmaps only; do not edit.\nwindow.GG_PANEL_FONTS='+json.dumps(out,separators=(',',':'))+';\n'
out_path=os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),'web','js','panel_fonts.js')
open(out_path,'w').write(js);print(out_path,len(js))
